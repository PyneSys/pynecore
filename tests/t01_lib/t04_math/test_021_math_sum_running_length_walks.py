# noinspection PyShadowingNames
def __test_math_sum_running_length_walks__(script_path, module_key):
    """
    Every running-length sum reproduces TradingView bit for bit on every bar.
    """
    import sys
    from pathlib import Path
    from pynecore.core.script_runner import ScriptRunner
    from pynecore.types.ohlcv import OHLCV

    sys.modules.pop(module_key, None)
    base_ts = 1_704_067_200_000  # 2024-01-01 00:00:00 UTC, in ms
    bars = [
        OHLCV(timestamp=base_ts + i * 1_800_000, open=o, high=h, low=lo, close=c, volume=v)
        for i, (o, h, lo, c, v) in enumerate(__test_helper_bars)
    ]
    runner = ScriptRunner(Path(script_path), iter(bars), __test_helper_make_syminfo())
    got = {name: [] for name in __test_helper_tv}
    for _candle, plot_data in runner.run_iter():
        for name, values in got.items():
            v = plot_data[name]
            values.append(None if v != v else v)
    for name, expected in __test_helper_tv.items():
        assert got[name] == expected, (name, got[name])
