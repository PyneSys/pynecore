"""
@pyne

Regression test: a grown ``math.sum`` window admits the raw values newest first
down to the offset one PAST the new window, then the ordinary fused step evicts
that offset with its ORIGINAL entry, and admitted bars keep their original
entries for later evictions.

Measured on CAPITALCOM:EURUSD 30m (probes wg/wh/wk: 131 isolated grows of
volume-scaled, ratio and raw volume sources, every one bit-exact on all
historical bars this way). The bars and expected sums below are TradingView's
own, from the first 110 bars of that chart (probe wt).
"""
from pynecore.lib import bar_index, close, high, low, math, open, plot, script, volume


@script.indicator("Math Sum Grow Admits Past Window")
def main():
    dv = (close - open) * volume
    plot(math.sum(dv, 5 if bar_index < 45 else 30), 'g1')
    plot(math.sum(dv, 20 if bar_index < 50 else 45), 'g2')
    plot(math.sum(dv, 10 if bar_index < 55 else 13), 'g3')
    plot(math.sum(close * volume, 8 if bar_index < 42 else 25), 'g4')
    plot(math.sum((high - low) / close, 7 if bar_index < 38 else 19), 'g5')


