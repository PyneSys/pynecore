"""
No new uncoded error in the runtime: every ``raise`` of a Python or a custom
exception without a code, and every ``assert``, under ``lib/``, ``types/`` and
``core/`` (without the broker and plugin APIs) is on the allowlist
``uncoded_allowlist.txt``, and the list only shrinks.

A user's error gets a code of the registry; an invariant of the runtime stays
uncoded and is reported as ``I0004``. Run this file with
``PYNE_UPDATE_UNCODED=1`` to rewrite the list after an uncoded place was removed.
"""
import ast
import builtins
import importlib
import os
from collections import Counter
from pathlib import Path


from pynecore.core.errors import PyneError

#: The package the scan reads
__test_helper_PACKAGE = Path(importlib.import_module('pynecore').__file__).resolve().parent
#: The areas the scan covers, and the API trees it leaves out
__test_helper_AREAS = ('lib', 'types', 'core')
__test_helper_SKIPPED = (('core', 'broker'), ('core', 'plugin'))
#: The allowlist: one line per place, ``path qualname kind count``
__test_helper_ALLOWLIST = Path(__file__).with_name('uncoded_allowlist.txt')


def __test_helper_module_globals(path: Path) -> dict:
    """The globals of the module at ``path``, to resolve a raised name."""
    parts = path.relative_to(__test_helper_PACKAGE.parent).with_suffix('').parts
    name = '.'.join(parts[:-1] if parts[-1] == '__init__' else parts)
    return vars(importlib.import_module(name))


def __test_helper_uncoded(name: str, module: dict) -> bool:
    """Whether raising ``name`` in ``module`` raises an exception without a code."""
    value = module.get(name, getattr(builtins, name, None))
    if not isinstance(value, type) or not issubclass(value, BaseException):
        # A helper that builds the coded error, or a caught exception raised again
        return False
    return not issubclass(value, PyneError)


def __test_helper_places() -> Counter:
    """Every uncoded ``raise`` and every ``assert`` of the covered areas, by
    ``(path, qualname, kind)``."""
    found: Counter = Counter()
    for area in __test_helper_AREAS:
        for path in sorted((__test_helper_PACKAGE / area).rglob('*.py')):
            rel = path.relative_to(__test_helper_PACKAGE)
            if any(rel.parts[:len(skip)] == skip for skip in __test_helper_SKIPPED):
                continue
            tree = ast.parse(path.read_text(encoding='utf-8'))
            module = __test_helper_module_globals(path)

            def visit(node: ast.AST, scope: tuple[str, ...]) -> None:
                for child in ast.iter_child_nodes(node):
                    if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                        visit(child, scope + (child.name,))
                        continue
                    qualname = '.'.join(scope) or '<module>'
                    if isinstance(child, ast.Assert):
                        found[(rel.as_posix(), qualname, 'assert')] += 1
                    elif isinstance(child, ast.Raise) and child.exc is not None:
                        target = child.exc.func if isinstance(child.exc, ast.Call) else child.exc
                        name = target.attr if isinstance(target, ast.Attribute) \
                            else getattr(target, 'id', None)
                        if name is not None and __test_helper_uncoded(name, module):
                            found[(rel.as_posix(), qualname, name)] += 1
                    visit(child, scope)

            visit(tree, ())
    return found


def __test_helper_allowed() -> Counter:
    """The allowlist's places and counts."""
    allowed: Counter = Counter()
    for line in __test_helper_ALLOWLIST.read_text(encoding='utf-8').splitlines():
        if line.strip() and not line.startswith('#'):
            path, qualname, kind, count = line.split()
            allowed[(path, qualname, kind)] = int(count)
    return allowed


def __test_helper_write(places: Counter) -> None:
    """Rewrite the allowlist with ``places``."""
    lines = ["# Uncoded raises and asserts of the runtime: path qualname kind count.",
             "# Generated by test_090_uncoded_ratchet.py (PYNE_UPDATE_UNCODED=1); it only shrinks."]
    lines += [f"{path} {qualname} {kind} {count}"
              for (path, qualname, kind), count in sorted(places.items())]
    __test_helper_ALLOWLIST.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def __test_no_new_uncoded_error_in_the_runtime__():
    """No place raises an uncoded error or asserts more often than the allowlist
    holds, and the allowlist holds no place that is gone"""
    places = __test_helper_places()
    if os.environ.get('PYNE_UPDATE_UNCODED') == '1':
        allowed = __test_helper_allowed() if __test_helper_ALLOWLIST.is_file() else places
        grown = {k: v for k, v in places.items() if v > allowed.get(k, 0)}
        assert not grown, f"the update only shrinks the list; new places: {sorted(grown)}"
        __test_helper_write(places)
        return
    allowed = __test_helper_allowed()
    new = sorted(f"{p} {q} {k}: {n} (allowed {allowed.get((p, q, k), 0)})"
                 for (p, q, k), n in places.items() if n > allowed.get((p, q, k), 0))
    assert not new, ("an uncoded error was added; give it a code of the registry, or, "
                     "for an invariant of the runtime, an explicit reason in review:\n"
                     + "\n".join(new))
    gone = sorted(f"{p} {q} {k}: {n} -> {places.get((p, q, k), 0)}"
                  for (p, q, k), n in allowed.items() if places.get((p, q, k), 0) < n)
    assert not gone, ("the allowlist holds places that are gone; run this test with "
                      "PYNE_UPDATE_UNCODED=1:\n" + "\n".join(gone))
